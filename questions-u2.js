// Small helper that draws a labelled line graph as inline SVG.
function graph({ xlab, ylab, xmax, ymax, xstep, ystep, pts, color = "#1d6fd6" }) {
  const W = 340, H = 210, L = 46, B = 34, T = 12, R = 14;
  const pw = W - L - R, ph = H - T - B;
  const X = x => L + (x / xmax) * pw, Y = y => T + ph - (y / ymax) * ph;
  let g = "";
  for (let x = 0; x <= xmax + 1e-9; x += xstep)
    g += `<line x1="${X(x)}" y1="${T}" x2="${X(x)}" y2="${T + ph}" stroke="#e3e9f3"/><text x="${X(x)}" y="${T + ph + 14}" font-size="10" text-anchor="middle" fill="#5b6880">${+x.toFixed(2)}</text>`;
  for (let y = 0; y <= ymax + 1e-9; y += ystep)
    g += `<line x1="${L}" y1="${Y(y)}" x2="${L + pw}" y2="${Y(y)}" stroke="#e3e9f3"/><text x="${L - 6}" y="${Y(y) + 3}" font-size="10" text-anchor="end" fill="#5b6880">${+y.toFixed(2)}</text>`;
  const path = pts.map(([x, y]) => `${X(x).toFixed(1)},${Y(y).toFixed(1)}`).join(" ");
  return `<svg class="graph" viewBox="0 0 ${W} ${H}" role="img" aria-label="${ylab} against ${xlab}">
    ${g}<line x1="${L}" y1="${T + ph}" x2="${L + pw}" y2="${T + ph}" stroke="#152033"/><line x1="${L}" y1="${T}" x2="${L}" y2="${T + ph}" stroke="#152033"/>
    <polyline points="${path}" fill="none" stroke="${color}" stroke-width="3" stroke-linejoin="round" stroke-linecap="round"/>
    <text x="${L + pw / 2}" y="${H - 4}" font-size="11" text-anchor="middle" fill="#152033">${xlab}</text>
    <text x="12" y="${T + ph / 2}" font-size="11" text-anchor="middle" fill="#152033" transform="rotate(-90 12 ${T + ph / 2})">${ylab}</text></svg>`;
}
const curve = (f, x0, x1, n = 20) => Array.from({ length: n + 1 }, (_, i) => { const x = x0 + (x1 - x0) * i / n; return [x, f(x)]; });

